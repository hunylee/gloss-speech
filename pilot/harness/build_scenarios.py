with open(ROOT.parent / "data" / "phrasebank.csv", encoding="utf-8") as f:
    bank = list(csv.DictReader(f))

for dom, cats in P.items():
    utts = [{"text": r["text"], "gold": r["gloss"], "category": "fixed", "split": "fixed"}
            for r in bank if r["domain"] == dom]
    for cat in ("paraphrase", "free"):
        rows = cats[cat]
        explicit = any(len(r) == 3 for r in rows)      # split을 직접 적은 상황은 나머지를 모두 dev로
        half = len(rows) // 2
        for i, r in enumerate(rows):
            t, g = r[0], r[1]
            split = r[2] if len(r) == 3 else ("dev" if explicit or i < half else "holdout")
            utts.append({"text": t, "gold": g, "category": cat, "split": split})
    # 실제 진행처럼 섞는다: 정형 문장 사이사이에 변형·자유 발화
    fixed = [u for u in utts if u["category"] == "fixed"]
    other = [u for u in utts if u["category"] != "fixed"]
    mixed, j = [], 0
    for i, u in enumerate(fixed):
        mixed.append(u)
        if i % 1 == 0 and j < len(other):
            mixed.append(other[j]); j += 1
    mixed += other[j:]
    (ROOT / "scenarios" / f"{dom}.json").write_text(
        json.dumps({"domain": dom, "utterances": mixed}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(dom, len(mixed), "utterances")
